"""Build the JSON portfolio and Markdown Log as a static website."""
from __future__ import annotations

import argparse
from datetime import date, datetime
import json
import math
from pathlib import Path
import re
import shutil
import sys
import hashlib
import unicodedata
from urllib.parse import urlsplit

from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape
from markdown_it import MarkdownIt
import yaml

if __package__:
    from .portfolio import load_portfolio
else:
    from portfolio import load_portfolio

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/build.py; edit content/ or src/ instead. -->\n'
DESCRIPTION = 'Technology, experiences, and observations—in writing and video.'


def plain_inline(token):
    return ''.join(child.content if child.type not in ('softbreak', 'hardbreak') else ' '
                   for child in (token.children or [])
                   if child.type in ('text', 'code_inline', 'image', 'softbreak', 'hardbreak'))


def render_markdown(body):
    parser = MarkdownIt('js-default', {'typographer': False})
    tokens = parser.parse(body)
    headings, used = [], set()
    for index, token in enumerate(tokens):
        if token.type != 'heading_open':
            continue
        # The front-matter title is the page's only H1.
        level = max(2, int(token.tag[1:]))
        token.tag = f'h{level}'
        tokens[index + 2].tag = token.tag
        text = plain_inline(tokens[index + 1])
        normalized = unicodedata.normalize('NFKC', text).lower()
        base = ''.join(char if unicodedata.category(char)[0] in 'LNM' or char in '_-' else '-'
                       for char in normalized)
        base = re.sub('-+', '-', base).strip('-') or 'section'
        anchor, suffix = f'section-{base}', 2
        while anchor in used:
            anchor = f'section-{base}-{suffix}'
            suffix += 1
        used.add(anchor)
        token.attrSet('id', anchor)
        token.attrSet('tabindex', '-1')
        if level <= 3:
            headings.append({'id': anchor, 'text': text, 'level': level})
    rendered = parser.renderer.render(tokens, parser.options, {})
    rendered = rendered.replace('<table>', '<div class="table-scroll" tabindex="0" role="region" aria-label="Table"><table>')
    rendered = rendered.replace('</table>', '</table></div>')
    words = sum(len(re.findall(r'\w+', token.content)) for token in tokens if token.type in ('inline', 'fence', 'code_block'))
    return rendered, headings, max(1, math.ceil(words / 200))


def read_post(path):
    source = path.read_text(encoding='utf-8-sig')
    match = re.match(r'\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z', source, re.S)
    if not match:
        raise ValueError(f'{path.name}: begin with YAML front matter between --- lines.')
    metadata = yaml.safe_load(match[1])
    if not isinstance(metadata, dict):
        raise ValueError(f'{path.name}: front matter must contain named fields.')
    for field in ('title', 'summary', 'category'):
        if not isinstance(metadata.get(field), str) or not metadata[field].strip():
            raise ValueError(f'{path.name}: {field} must be a non-empty string.')
    published = metadata.get('date')
    if isinstance(published, datetime):
        published = published.date()
    if isinstance(published, str):
        try:
            published = date.fromisoformat(published)
        except ValueError as exc:
            raise ValueError(f'{path.name}: date must use YYYY-MM-DD.') from exc
    if not isinstance(published, date):
        raise ValueError(f'{path.name}: date must use YYYY-MM-DD.')
    draft = metadata.get('draft', False)
    if not isinstance(draft, bool):
        raise ValueError(f'{path.name}: draft must be true or false, without quotes.')
    sample = metadata.get('sample', False)
    if not isinstance(sample, bool):
        raise ValueError(f'{path.name}: sample must be true or false.')
    youtube = metadata.get('youtube', '')
    if not isinstance(youtube, str):
        raise ValueError(f'{path.name}: youtube must be a URL string.')
    if youtube:
        url = urlsplit(youtube)
        if url.scheme != 'https' or url.hostname not in ('youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be') or url.username or url.password:
            raise ValueError(f'{path.name}: youtube must be an HTTPS YouTube link.')
    content_type = metadata.get('type', 'Article')
    if not isinstance(content_type, str) or content_type.lower() not in ('article', 'video'):
        raise ValueError(f'{path.name}: type must be Article or Video.')
    content_type = content_type.capitalize()
    slug = path.stem
    if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
        raise ValueError(f'{path.name}: use lowercase letters, numbers, and hyphens in filenames.')
    if not match[2].strip() and (content_type != 'Video' or not youtube):
        raise ValueError(f'{path.name}: the article body is empty.')
    rendered, headings, reading_time = render_markdown(match[2])
    return dict(title=metadata['title'].strip(), summary=metadata['summary'].strip(),
                category=metadata['category'].strip(), date=published,
                display_date=f'{published.strftime("%b")} {published.day}, {published.year}',
                slug=slug, draft=draft, html=rendered, headings=headings,
                reading_time=reading_time, sample=sample, youtube=youtube, content_type=content_type)


def collect_posts(folder):
    posts = [read_post(path) for path in sorted(folder.glob('*.md'))]
    return sorted((post for post in posts if not post['draft']),
                  key=lambda post: (post['date'], post['slug']), reverse=True)


def build(root=ROOT):
    root = root.resolve()
    output = root / '_site'
    # This is the sole generated directory; never clean a source directory or symlink target.
    if output.is_symlink() or output.resolve() != root / '_site':
        raise ValueError('The _site output directory must not be a symlink or junction.')
    # Validate and render everything before changing any generated pages.
    portfolio, photo_url = load_portfolio(root)
    posts = collect_posts(root / 'content' / 'posts')
    env = Environment(loader=FileSystemLoader(root / 'src' / 'templates' / 'log'),
                      autoescape=select_autoescape(['html']), trim_blocks=True, lstrip_blocks=True)
    env.globals.update(profile=portfolio['profile'], year=date.today().year)
    index_template = env.get_template('index.html')
    article_template = env.get_template('article.html')
    files = {'log.html': MARKER + index_template.render(
        title='Tafhim’s Log', description=DESCRIPTION,
        page_path='log.html', prefix='', post=None, posts=posts,
        categories=sorted({post['category'] for post in posts}))}
    files['post.html'] = MARKER + env.get_template('redirect.html').render(
        title='Open Log entry', description=DESCRIPTION,
        page_path='log.html', prefix='', post=None)
    redirect_template = env.get_template('legacy.html')
    def legacy_redirect(target, prefix=''):
        return MARKER + redirect_template.render(target=prefix + target,
            page_path=target, prefix=prefix)
    files['blog.html'] = legacy_redirect('log.html')
    files['blog/index.html'] = legacy_redirect('log.html', '../')
    for index, post in enumerate(posts):
        page_path = f'log/{post["slug"]}.html'
        files[page_path] = MARKER + article_template.render(
            title=post['title'], description=post['summary'], page_path=page_path,
            prefix='../', post=post, others=[item for item in posts if item != post],
            newer=posts[index - 1] if index else None,
            older=posts[index + 1] if index + 1 < len(posts) else None)
        files[f'blog/{post["slug"]}.html'] = legacy_redirect(page_path, '../')
    files['data/log-index.json'] = json.dumps(
        [{'slug': post['slug'], 'title': post['title'], 'type': post['content_type']} for post in posts], ensure_ascii=False, indent=2) + '\n'
    historical = root / 'content' / 'legacy-urls.json'
    if historical.exists():
        for slug in json.loads(historical.read_text(encoding='utf-8')):
            if not isinstance(slug, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
                raise ValueError('Invalid slug in content/legacy-urls.json.')
            files.setdefault(f'blog/{slug}.html', legacy_redirect('log.html', '../'))
    # A stable resume URL with a content-based version avoids stale cached downloads.
    resume = root / 'public' / 'resume' / 'resume.pdf'
    resume_url = None
    if resume.exists():
        if not resume.is_file() or not resume.read_bytes().startswith(b'%PDF-'):
            raise ValueError('public/resume/resume.pdf must be a PDF file.')
        version = hashlib.sha256(resume.read_bytes()).hexdigest()[:12]
        resume_url = f'resume/resume.pdf?v={version}'
    page_env = Environment(loader=FileSystemLoader([root / 'src' / 'pages', root / 'src' / 'templates']),
                           autoescape=select_autoescape(['html']), undefined=StrictUndefined,
                           trim_blocks=True, lstrip_blocks=True)
    for page in (root / 'src' / 'pages').glob('*.html'):
        files[page.name] = MARKER + page_env.get_template(page.name).render(
            resume_url=resume_url, portfolio=portfolio, photo_url=photo_url, year=date.today().year)
    public = root / 'public'
    public_files = []
    for asset in public.rglob('*'):
        if asset.is_symlink() or public.resolve() not in asset.resolve().parents:
            raise ValueError(f'Symlinks are not supported in public/: {asset.name}')
        if asset.is_file() and asset.suffix.lower() != '.md':
            public_files.append(asset)
    # All validation/rendering precedes cleanup. _site is exclusively disposable build output.
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    for asset in public_files:
        destination = output / asset.relative_to(public)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(asset, destination)
    (output / '.nojekyll').touch()
    for relative, content in files.items():
        destination = output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding='utf-8')
    print(f'Built {len(posts)} Log entries in {output}')
    return posts


if __name__ == '__main__':
    cli = argparse.ArgumentParser(description=__doc__)
    args = cli.parse_args()
    try:
        build()
    except (ValueError, yaml.YAMLError) as exc:
        print(f'Site build failed: {exc}', file=sys.stderr)
        sys.exit(1)
